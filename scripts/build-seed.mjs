import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'data/seed')

function readCsv(name) {
  const [head, ...lines] = fs.readFileSync(path.join(dir, name), 'utf8').trim().split(/\r?\n/)
  const cols = head.split(',')
  return lines.map((l) => Object.fromEntries(l.split(',').map((v, i) => [cols[i], v.trim()])))
}

const distributors = readCsv('distributor_master.csv').map((r) => ({
  id: r.Distributor_ID,
  name: r.Distributor_Name,
  region: r.Region,
  status: r.Status,
}))
const skus = readCsv('sku_master.csv').map((r) => ({
  id: r.SKU_ID,
  name: r.SKU_Name,
  category: r.Category,
  perishability: r.Perishability,
  standardQty: Number(r.Standard_Reorder_Qty),
  uom: r.Unit_of_Measure,
  distributorId: r.Distributor_ID,
}))
const sales = readCsv('weekly_sales.csv').map((r) => ({ skuId: r.SKU_ID, week: r.Week, units: Number(r.Units_Sold) }))
const inventory = readCsv('current_inventory.csv').map((r) => ({
  skuId: r.SKU_ID,
  location: r.Location,
  onHand: Number(r.Units_On_Hand),
  asOf: r.As_Of_Date,
}))
const calendar = readCsv('calendar.csv').map((r) => ({
  yearMonth: r.Year_Month,
  isFestival: r.Is_Festival_Month.toUpperCase() === 'TRUE',
}))

fs.writeFileSync(
  path.join(dir, 'seed.json'),
  JSON.stringify({ distributors, skus, sales, inventory, calendar }, null, 1) + '\n',
)

const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const sql = [
  '-- Generated by scripts/build-seed.mjs from data/seed/*.csv. Safe to re-run.',
  `insert into distributors (id, name, region, status) values\n${distributors
    .map((d) => `  (${q(d.id)}, ${q(d.name)}, ${q(d.region)}, ${q(d.status)})`)
    .join(',\n')}\non conflict (id) do update set name = excluded.name, region = excluded.region, status = excluded.status;`,
  `insert into skus (id, name, category, perishability, standard_reorder_qty, uom, distributor_id) values\n${skus
    .map((s) => `  (${q(s.id)}, ${q(s.name)}, ${q(s.category)}, ${q(s.perishability)}, ${s.standardQty}, ${q(s.uom)}, ${q(s.distributorId)})`)
    .join(',\n')}\non conflict (id) do update set name = excluded.name, category = excluded.category, perishability = excluded.perishability, standard_reorder_qty = excluded.standard_reorder_qty, uom = excluded.uom, distributor_id = excluded.distributor_id;`,
  `insert into weekly_sales (sku_id, week, units_sold) values\n${sales
    .map((s) => `  (${q(s.skuId)}, ${q(s.week)}, ${s.units})`)
    .join(',\n')}\non conflict (sku_id, week) do update set units_sold = excluded.units_sold;`,
  `insert into inventory (sku_id, location, units_on_hand, as_of_date) values\n${inventory
    .map((i) => `  (${q(i.skuId)}, ${q(i.location)}, ${i.onHand}, ${q(i.asOf)})`)
    .join(',\n')}\non conflict (sku_id) do update set location = excluded.location, units_on_hand = excluded.units_on_hand, as_of_date = excluded.as_of_date;`,
  `insert into calendar (year_month, is_festival_month) values\n${calendar
    .map((c) => `  (${q(c.yearMonth)}, ${c.isFestival})`)
    .join(',\n')}\non conflict (year_month) do update set is_festival_month = excluded.is_festival_month;`,
].join('\n\n')

fs.writeFileSync(path.join(root, 'supabase/seed.sql'), sql + '\n')
console.log(`seed.json + seed.sql written: ${skus.length} skus, ${sales.length} sales rows`)
